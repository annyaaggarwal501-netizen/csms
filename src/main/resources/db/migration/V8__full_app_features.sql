-- V8__full_app_features.sql — tables and columns for the full application.

-- 1. Users: forced password change (first login / after a reset by the Owner) and last login time.
ALTER TABLE app_user ADD COLUMN must_change_password BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE app_user ADD COLUMN last_login_at TIMESTAMP NULL;

-- 2. Cost price at the moment of sale, so the profit report stays correct when cost prices change later.
ALTER TABLE sale_line ADD COLUMN unit_cost DECIMAL(10,2) NULL;
UPDATE sale_line sl SET unit_cost = v.cost_price FROM variant v WHERE v.variant_id = sl.variant_id;

-- 3. Customer credit (udhaar) ledger: every credit sale, repayment and reversal (REQ-CUS-5).
CREATE TABLE customer_credit_txn (
  txn_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES customer(customer_id),
  type        VARCHAR(12) NOT NULL CONSTRAINT chk_cct_type CHECK (type IN ('SALE','REPAYMENT','VOID')),
  amount      DECIMAL(10,2) NOT NULL CONSTRAINT chk_cct_amt CHECK (amount > 0),
  sale_id     BIGINT NULL REFERENCES sale(sale_id),
  mode        VARCHAR(12) NULL,                       -- how a repayment was paid: CASH, UPI, CARD
  note        VARCHAR(150) NULL,
  balance_after DECIMAL(10,2) NOT NULL,
  created_by  BIGINT NOT NULL REFERENCES app_user(user_id),
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_cct_customer ON customer_credit_txn(customer_id, created_at);

-- Credit sales made before this version get their ledger rows now, so balances match credit_due.
INSERT INTO customer_credit_txn (customer_id, type, amount, sale_id, note, balance_after, created_by, created_at)
SELECT s.customer_id, 'SALE', p.amount, s.sale_id, 'Credit sale ' || s.invoice_no, 0, s.created_by, s.completed_at
FROM payment p JOIN sale s ON s.sale_id = p.sale_id
WHERE p.mode = 'CREDIT' AND s.customer_id IS NOT NULL AND s.status <> 'CANCELLED';
UPDATE customer_credit_txn t SET balance_after = (
  SELECT SUM(CASE WHEN t2.type = 'SALE' THEN t2.amount ELSE -t2.amount END) FROM customer_credit_txn t2
  WHERE t2.customer_id = t.customer_id AND t2.txn_id <= t.txn_id);

-- 4. Activity log (REQ-ACC-6): logins, price changes, voids, stock adjustments, settings and user changes.
CREATE TABLE audit_log (
  audit_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NULL REFERENCES app_user(user_id),
  username   VARCHAR(30) NULL,
  action     VARCHAR(40) NOT NULL,
  entity     VARCHAR(30) NULL,
  entity_id  BIGINT NULL,
  details    VARCHAR(500) NULL,
  ip         VARCHAR(45) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_audit_created ON audit_log(created_at);

